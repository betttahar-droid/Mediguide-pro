def nano_palette(role: str, index: int) -> tuple[float, float, float, float]:
    audit = json.loads(NANO_AUDIT.read_text(encoding="utf-8"))
    entry = next(item for item in audit["materials"] if item["role"] == role)
    rgb = entry["paletteRgb"][index]
    return tuple(value / 255.0 for value in rgb) + (1.0,)


def source_atlas_placements() -> dict[str, tuple[int, int, int, int]]:
    """Return exact atlas rectangles generated by extract_fridge_source_atlas.py."""
    placements = {
        "front": (0, 0, 39, 96),
        "side": (40, 0, 37, 96),
        "back": (78, 0, 37, 96),
    }
    if not ATLAS.exists():
        raise FileNotFoundError(
            f"Missing {ATLAS}. Run tools/authoring/extract_fridge_source_atlas.py first."
        )
    return placements


def clear_scene() -> None:
    for obj in list(bpy.data.objects):
        bpy.data.objects.remove(obj, do_unlink=True)
    for mesh in list(bpy.data.meshes):
        bpy.data.meshes.remove(mesh)
    for material in list(bpy.data.materials):
        bpy.data.materials.remove(material)


def solid_material(name: str, rgba: tuple[float, float, float, float]):
    material = bpy.data.materials.new(name)
    material.diffuse_color = rgba
    material.use_nodes = True
    bsdf = material.node_tree.nodes.get("Principled BSDF")
    bsdf.inputs["Base Color"].default_value = rgba
    bsdf.inputs["Roughness"].default_value = 0.92
    bsdf.inputs["Alpha"].default_value = rgba[3]
    if rgba[3] < 1.0:
        material.surface_render_method = "DITHERED"
    return material


def source_material(image_path: Path = ATLAS):
    material = bpy.data.materials.new("source_pixels_locked")
    material.use_nodes = True
    material.use_backface_culling = True
    nodes = material.node_tree.nodes
    links = material.node_tree.links
    bsdf = nodes.get("Principled BSDF")
    image = bpy.data.images.load(str(image_path), check_existing=True)
    texture = nodes.new("ShaderNodeTexImage")
    texture.image = image
    texture.interpolation = "Closest"
    links.new(texture.outputs["Color"], bsdf.inputs["Base Color"])
    alpha_clip = nodes.new("ShaderNodeMath")
    alpha_clip.operation = "GREATER_THAN"
    alpha_clip.inputs[1].default_value = 0.5
    links.new(texture.outputs["Alpha"], alpha_clip.inputs[0])
    links.new(alpha_clip.outputs[0], bsdf.inputs["Alpha"])
    bsdf.inputs["Roughness"].default_value = 1.0
    return material


