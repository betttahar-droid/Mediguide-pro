def add_tiled_image_quad(name: str, material, points_px, uv_axes, parent, extras=None):
    """Map a 16px logical material field at exactly one texel per model pixel."""
    axis_index = {"x": 0, "y": 1, "z": 2}
    u_axis, v_axis = (axis_index[axis] for axis in uv_axes)
    mesh = bpy.data.meshes.new(name + "_mesh")
    bm = bmesh.new()
    uv_layer = bm.loops.layers.uv.verify()
    verts = [bm.verts.new(tuple(value / PPU for value in point)) for point in points_px]
    face = bm.faces.new(verts)
    for loop, point in zip(face.loops, points_px):
        loop[uv_layer].uv = (
            point[u_axis] / MATERIAL_TILE_PX,
            point[v_axis] / MATERIAL_TILE_PX,
        )
    bm.to_mesh(mesh)
    bm.free()
    obj = bpy.data.objects.new(name, mesh)
    bpy.context.scene.collection.objects.link(obj)
    obj.data.materials.append(material)
    obj.parent = parent
    if extras:
        for key, value in extras.items():
            obj[key] = value
    return obj


def add_box(name: str, bounds_px, material, parent, bevel_role: str):
    """Create an explicit six-face box through bmesh; no primitive operator."""
    x0, y0, z0, x1, y1, z1 = bounds_px
    coordinates = [
        (x0, y0, z0), (x1, y0, z0), (x1, y1, z0), (x0, y1, z0),
        (x0, y0, z1), (x1, y0, z1), (x1, y1, z1), (x0, y1, z1),
    ]
    indices = [
        (0, 3, 2, 1), (4, 5, 6, 7),
        (0, 1, 5, 4), (1, 2, 6, 5),
        (2, 3, 7, 6), (3, 0, 4, 7),
    ]
    mesh = bpy.data.meshes.new(name + "_mesh")
    bm = bmesh.new()
    uv_layer = bm.loops.layers.uv.verify()
    verts = [bm.verts.new(tuple(value / PPU for value in point)) for point in coordinates]
    for face_indices in indices:
        face = bm.faces.new([verts[index] for index in face_indices])
        face_points = [coordinates[index] for index in face_indices]
        spans = [max(point[axis] for point in face_points) - min(point[axis] for point in face_points)
                 for axis in range(3)]
        normal_axis = spans.index(min(spans))
        if isinstance(material, tuple):
            center = [sum(point[axis] for point in face_points) / len(face_points)
                      for axis in range(3)]
            if normal_axis == 2:
                face.material_index = 2 if center[2] > (z0 + z1) / 2 else 1
            elif normal_axis == 0:
                face.material_index = 1
            else:
                face.material_index = 0 if center[1] <= (y0 + y1) / 2 else 1
        u_axis, v_axis = ((1, 2) if normal_axis == 0 else
                          (0, 2) if normal_axis == 1 else (0, 1))
        for loop, point in zip(face.loops, face_points):
            loop[uv_layer].uv = (point[u_axis] / MATERIAL_TILE_PX,
                                 point[v_axis] / MATERIAL_TILE_PX)
    bm.to_mesh(mesh)
    bm.free()
    obj = bpy.data.objects.new(name, mesh)
    bpy.context.scene.collection.objects.link(obj)
    for item in material_sequence(material):
        obj.data.materials.append(item)
    obj.parent = parent
    obj["sourceGeometryRole"] = bevel_role
    return obj


def add_loft(name: str, rings, material, parent):
    """Create the structural hull from explicit width/depth/z source rings."""
    mesh = bpy.data.meshes.new(name + "_mesh")
    bm = bmesh.new()
    uv_layer = bm.loops.layers.uv.verify()

    def add_face(vertices):
        face = bm.faces.new(vertices)
        points = [[coordinate * PPU for coordinate in loop.vert.co] for loop in face.loops]
        spans = [max(point[axis] for point in points) - min(point[axis] for point in points)
                 for axis in range(3)]
        normal_axis = spans.index(min(spans))
        if isinstance(material, tuple):
            center = [sum(point[axis] for point in points) / len(points)
                      for axis in range(3)]
            if normal_axis == 2:
                face.material_index = 2
            elif normal_axis == 0:
                face.material_index = 1
            else:
                face.material_index = 0 if center[1] < 0 else 1
        u_axis, v_axis = ((1, 2) if normal_axis == 0 else
                          (0, 2) if normal_axis == 1 else (0, 1))
        for loop, point in zip(face.loops, points):
            loop[uv_layer].uv = (point[u_axis] / MATERIAL_TILE_PX,
                                 point[v_axis] / MATERIAL_TILE_PX)
        return face
    ring_verts = []
    for ring in rings:
        z, width, front_y, back_y = ring
        x = width / 2.0
        ring_verts.append([
            bm.verts.new((-x / PPU, front_y / PPU, z / PPU)),
            bm.verts.new(( x / PPU, front_y / PPU, z / PPU)),
            bm.verts.new(( x / PPU, back_y / PPU, z / PPU)),
            bm.verts.new((-x / PPU, back_y / PPU, z / PPU)),
        ])
    add_face(list(reversed(ring_verts[0])))
    add_face(ring_verts[-1])
    for segment_index, (lower, upper) in enumerate(zip(ring_verts, ring_verts[1:])):
        for index in range(4):
            lower_z = rings[segment_index][0]
            upper_z = rings[segment_index + 1][0]
            if index == 0 and lower_z >= 20.6 and upper_z <= 86.45:
                continue
            add_face((lower[index], lower[(index + 1) % 4], upper[(index + 1) % 4], upper[index]))
    bm.to_mesh(mesh)
    bm.free()
    obj = bpy.data.objects.new(name, mesh)
    bpy.context.scene.collection.objects.link(obj)
    for item in material_sequence(material):
        obj.data.materials.append(item)
    obj.parent = parent
    obj["sourceGeometryRole"] = "structural_hull"
    return obj


def add_conformal_source_skins(rings, material, parent):
    """Bind source pixels to the measured front/right/back hull surfaces."""
    def finish(name, bm):
        mesh = bpy.data.meshes.new(name + "_mesh")
        bm.to_mesh(mesh)
        bm.free()
        obj = bpy.data.objects.new(name, mesh)
        bpy.context.scene.collection.objects.link(obj)
        obj.data.materials.append(material)
        obj.parent = parent
        obj["texturePolicy"] = "geometry_bound_source_pixels"
        return obj

    # Front: each row uses the matching visible atlas interval rather than
    # stretching all 39 atlas pixels into a narrower crown row.
    bm = bmesh.new(); uv_layer = bm.loops.layers.uv.verify()
    front_rows = []
    for z, width, front_y, _ in rings:
        half = width / 2
        u0, u1 = 19.5 - half, 19.5 + half
        front_rows.append((
            bm.verts.new((-half / PPU, (front_y - .60) / PPU, z / PPU)),
            bm.verts.new(( half / PPU, (front_y - .60) / PPU, z / PPU)),
            u0, u1, 96 - z,
        ))
    for lower, upper in zip(front_rows, front_rows[1:]):
        face = bm.faces.new((lower[0], lower[1], upper[1], upper[0]))
        for loop, uv_px in zip(face.loops, ((lower[2],lower[4]),(lower[3],lower[4]),(upper[3],upper[4]),(upper[2],upper[4]))):
            loop[uv_layer].uv = (uv_px[0]/ATLAS_SIZE, 1-uv_px[1]/ATLAS_SIZE)
    finish("source_skin_front", bm)

    # Right side: vertices follow both the depth taper and the width profile.
    bm = bmesh.new(); uv_layer = bm.loops.layers.uv.verify(); side_rows=[]
    for z, width, front_y, back_y in rings:
        x = width / 2 + .08
        side_rows.append((
            bm.verts.new((x/PPU, (front_y+2.2)/PPU, z/PPU)),
            bm.verts.new((x/PPU, back_y/PPU, z/PPU)), 96-z,
        ))
    for lower, upper in zip(side_rows, side_rows[1:]):
        face = bm.faces.new((lower[0], lower[1], upper[1], upper[0]))
        for loop, uv_px in zip(face.loops, ((74,lower[2]),(40,lower[2]),(40,upper[2]),(74,upper[2]))):
            loop[uv_layer].uv = (uv_px[0]/ATLAS_SIZE, 1-uv_px[1]/ATLAS_SIZE)
    finish("source_skin_side_right", bm)

    # Back follows the same profile instead of remaining a floating rectangle.
    bm = bmesh.new(); uv_layer = bm.loops.layers.uv.verify(); back_rows=[]
    for z, width, _, back_y in rings:
        half = width / 2
        back_rows.append((
            bm.verts.new(( half/PPU, (back_y+.08)/PPU, z/PPU)),
            bm.verts.new((-half/PPU, (back_y+.08)/PPU, z/PPU)), 96-z,
        ))
    for lower, upper in zip(back_rows, back_rows[1:]):
        face = bm.faces.new((lower[0], lower[1], upper[1], upper[0]))
        for loop, uv_px in zip(face.loops, ((78,lower[2]),(115,lower[2]),(115,upper[2]),(78,upper[2]))):
            loop[uv_layer].uv = (uv_px[0]/ATLAS_SIZE, 1-uv_px[1]/ATLAS_SIZE)
    finish("source_skin_back", bm)


def add_conformal_side_panel(rings, material, parent):
    """Tile the clean steel field only over the real side-panel vertical band."""
    panel_rings = [ring for ring in rings if 20.6 <= ring[0] <= 86.45]
    bm = bmesh.new()
    uv_layer = bm.loops.layers.uv.verify()
    rows = []
    for z, width, front_y, back_y in panel_rings:
        x = width / 2 + .08
        rows.append((
            bm.verts.new((x/PPU, (front_y+2.2)/PPU, z/PPU)),
            bm.verts.new((x/PPU, back_y/PPU, z/PPU)), z, front_y+2.2, back_y,
        ))
    for lower, upper in zip(rows, rows[1:]):
        face = bm.faces.new((lower[0], lower[1], upper[1], upper[0]))
        for loop, uv_px in zip(face.loops, (
            (lower[3], lower[2]), (lower[4], lower[2]),
            (upper[4], upper[2]), (upper[3], upper[2]),
        )):
            loop[uv_layer].uv = (uv_px[0]/PANEL_TILE_PX, uv_px[1]/PANEL_TILE_PX)
    mesh = bpy.data.meshes.new("nano_tile_side_panel_mesh")
    bm.to_mesh(mesh)
    bm.free()
    obj = bpy.data.objects.new("nano_tile_side_panel", mesh)
    bpy.context.scene.collection.objects.link(obj)
    obj.data.materials.append(material)
    obj.parent = parent
    obj["texturePolicy"] = "TILE_WORLD_SCALE"
    return obj


