def add_quad(name: str, material, points_px, uv_px, parent, extras=None):
    mesh = bpy.data.meshes.new(name + "_mesh")
    bm = bmesh.new()
    uv_layer = bm.loops.layers.uv.verify()
    verts = [bm.verts.new(tuple(value / PPU for value in point)) for point in points_px]
    face = bm.faces.new(verts)
    for loop, (u_px, v_top_px) in zip(face.loops, uv_px):
        loop[uv_layer].uv = (u_px / ATLAS_SIZE, 1.0 - (v_top_px / ATLAS_SIZE))
    bm.to_mesh(mesh)
    bm.free()
    obj = bpy.data.objects.new(name, mesh)
    bpy.context.scene.collection.objects.link(obj)
    obj.data.materials.append(material)
    obj.parent = parent
    if extras:
        for key, value in extras.items():
            obj[key] = value
    return obj


