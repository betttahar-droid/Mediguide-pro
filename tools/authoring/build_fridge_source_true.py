def tiled_material(name: str, image_path: Path):
    """Unlit-neutral material field that repeats in model-pixel space."""
    material = image_surface_material(name, image_path)
    texture = next(node for node in material.node_tree.nodes if node.type == "TEX_IMAGE")
    texture.extension = "REPEAT"
    return material


def tiled_material_set(name: str, image_path: Path):
    """Front/side/top value steps sharing one Nano-authored motif layout."""
    suffix = f"-microtile-{NANO_VERSION}.png"
    stem = image_path.name.replace(suffix, "")
    side_path = image_path.with_name(f"{stem}-side{suffix}")
    top_path = image_path.with_name(f"{stem}-top{suffix}")
    return (
        tiled_material(f"{name}_front", image_path),
        tiled_material(f"{name}_side", side_path),
        tiled_material(f"{name}_top", top_path),
    )


