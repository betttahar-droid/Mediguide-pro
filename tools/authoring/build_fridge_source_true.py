def build(out_path: Path = OUT, root_name: str = "vaccine_fridge_source_true_root",
          root_extras: dict | None = None):
    placements = source_atlas_placements()
    clear_scene()
    root = bpy.data.objects.new(root_name, None)
    bpy.context.scene.collection.objects.link(root)
    root["pixelsPerUnit"] = AUTHORITY["pixelsPerUnit"]
    root["authoritySha256"] = AUTHORITY["authoritySha256"]
    root["sourceTruthVersion"] = AUTHORITY["schemaVersion"]
    root["adaptivePolicy"] = AUTHORITY["adaptive"]["policy"]
    root["doorBayWidthPx"] = AUTHORITY["adaptive"]["doorBayWidthPx"]
    if root_extras:
        for key, value in root_extras.items():
            root[key] = value

    materials = {
        key: solid_material(f"structure_{key}", tuple(rgba))
        for key, rgba in AUTHORITY["materials"].items()
    }
    cream_tile = tiled_material_set("nano_cream_microfield", NANO_CREAM_TILE)
    steel_tile = tiled_material_set("nano_steel_microfield", NANO_STEEL_TILE)
    steel_panel_tile = tiled_material("nano_steel_panel_microfield", NANO_STEEL_PANEL_TILE)
    teal_tile = tiled_material_set("nano_teal_microfield", NANO_TEAL_TILE)
    materials.update({"cream": cream_tile, "steel": steel_tile, "teal": teal_tile})
    reflection = image_decal_material("source_glass_reflection", GLASS_OVERLAY)
    display_pixels = image_surface_material("source_display_pixels", DISPLAY_TEXTURE)
    grille_pixels = image_surface_material("source_grille_pixels", GRILLE_TEXTURE)

    # Explicit profile rings measured from the locked front and side silhouettes.
    add_loft("source_hull", SOURCE_RINGS, materials["steel"], root)

    # Unique structural parts are assembled from the canonical grid spec.
    # Generated correction sheets remain advisory until their measurements are
    # accepted into that spec, so image-model drift cannot silently alter a GLB.
    for part in AUTHORITY["parts"]:
        add_box(part["name"], part["boundsPx"], materials[part["material"]], root, part["role"])

    # Repeated parts use one measured template rather than independent copies.
    shelf_spec = AUTHORITY["shelfTemplate"]
    for shelf_z in shelf_spec["elevationsPx"]:
        body = list(shelf_spec["bodyBoundsPx"])
        lip = list(shelf_spec["lipBoundsPx"])
        body[2] += shelf_z
        body[5] += shelf_z
        lip[2] += shelf_z
        lip[5] += shelf_z
        add_box(f"shelf_{shelf_z}", body, materials[shelf_spec["bodyMaterial"]], root, "shelf")
        add_box(f"shelf_lip_{shelf_z}", lip, materials[shelf_spec["lipMaterial"]], root, "shelf_front_lip")

    image_materials = {
        "glassReflection": reflection,
    }
    for surface in AUTHORITY["imageSurfaces"]:
        if surface["name"] == "source_top_surface":
            add_tiled_image_quad(
                "nano_tile_top_surface", cream_tile[2], surface["pointsPx"], ("x", "y"), root,
                {"texturePolicy": "TILE_WORLD_SCALE_16PX", "generatedSource": "nano-banana-2"},
            )
            continue
        add_image_quad(surface["name"], image_materials[surface["texture"]],
                       surface["pointsPx"], root,
                       {"texturePolicy": surface["texturePolicy"]})

    # Structural surfaces use clean generated material fields. Full-view source
    # skins are intentionally absent: their baked frame, crown, seam and shadow
    # pixels would duplicate geometry and create the small edge errors this
    # pipeline is designed to reject.
    add_conformal_side_panel(SOURCE_RINGS, steel_panel_tile, root)
    add_conformal_back_panel(SOURCE_RINGS, steel_panel_tile, root)
    add_panel_detail_decals(SOURCE_RINGS, root)
    add_front_style_details([0.0], shelf_spec["elevationsPx"], root)
    add_top_style_details(root)
    if ENABLE_NANO_DECAL_EXPERIMENT:
        add_nano_margin_decals(SOURCE_RINGS, shelf_spec["elevationsPx"], root)
    if ENABLE_STYLE_FIT_V7:
        add_style_fit_geometry_v7(root)
        add_nano_style_motifs_v7(SOURCE_RINGS, shelf_spec["elevationsPx"], root)
    if ENABLE_PS1_DECAL_STYLE_V8:
        add_ps1_decal_details_v8(SOURCE_RINGS, shelf_spec["elevationsPx"], root)

    x0, x1, z0, z1 = AUTHORITY["frontFeaturesPx"]["display"]
    add_image_quad("fixed_display", display_pixels,
                   [(x0,-16.02,z0),(x1,-16.02,z0),(x1,-16.02,z1),(x0,-16.02,z1)], root,
                   {"texturePolicy":"FIXED_CENTER_1TO1"})
    x0, x1, z0, z1 = AUTHORITY["frontFeaturesPx"]["grille"]
    add_image_quad("fixed_grille", grille_pixels,
                   [(x0,-15.68,z0),(x1,-15.68,z0),(x1,-15.68,z1),(x0,-15.68,z1)], root,
                   {"texturePolicy":"FIXED_PER_BAY_1TO1"})

    for name, position in AUTHORITY["socketsPx"].items():
        socket = bpy.data.objects.new(name, None)
        bpy.context.scene.collection.objects.link(socket)
        socket.parent = root
        socket.location = tuple(value / PPU for value in position)
        socket["restPositionPx"] = list(position)
        socket["adaptivePolicy"] = "translate_only_keep_scale_1"

    out_path.parent.mkdir(parents=True, exist_ok=True)
    for obj in bpy.context.scene.objects:
        obj.select_set(True)
    bpy.context.view_layer.objects.active = root
    bpy.ops.export_scene.gltf(
        filepath=str(out_path), export_format="GLB", use_selection=True,
        export_yup=True, export_materials="EXPORT", export_extras=True,
    )
    # Blender's Closest sampler exports NEAREST_MIPMAP_NEAREST.  Source pixels
    # must not acquire generated mip levels in Three.js, so patch the same-size
    # JSON token to plain NEAREST without disturbing GLB chunk offsets.
    glb_bytes = out_path.read_bytes()
    glb_bytes = glb_bytes.replace(b'"minFilter":9984', b'"minFilter":9728')
    out_path.write_bytes(glb_bytes)
    print(json.dumps({
        "model": str(out_path),
        "materialTiles": [str(NANO_CREAM_TILE), str(NANO_STEEL_TILE)],
        "sourceSha256": AUTHORITY["authoritySha256"],
        "schemaVersion": AUTHORITY["schemaVersion"],
        "dimensionsPx": [39, 37, 96],
    }, indent=2))


if __name__ == "__main__":
    build()
